def main(stdscr):
    # Hide the blinking text cursor
    curses.curs_set(0)
    stdscr.clear()

    # Get maximum screen dimensions
    screen_height, screen_width = stdscr.getmaxyx()
    
    # Process the art lines cleanly
    art_lines = ASCII_ART.splitlines()
    art_height = len(art_lines)
    art_width = max(len(line) for line in art_lines) if art_lines else 0

    # SAFETY CHECK: Prevent crashes if the art string formatting is empty
    if art_height == 0 or art_width == 0:
        stdscr.addstr(0, 0, "No ASCII art found to display.")
        stdscr.refresh()
        stdscr.getch()
        return

    # Use a 'Pad' to safely handle art sizes larger than the physical screen window
    # We add 1 extra line safety margin to prevent bottom-right edge crash rules
    pad = curses.newpad(art_height + 1, art_width + 1)
    
    # Write the raw lines to our virtual canvas
    for i, line in enumerate(art_lines):
        try:
            pad.addstr(i, 0, line)
        except curses.error:
            pass # Keep going if text encounters structural edge limitations

    # Calculate bounded screen viewport windows to avoid rendering off-canvas constraints
    render_h = min(art_height, screen_height - 1)
    render_w = min(art_width, screen_width - 1)

    # Render viewport: (pad_y, pad_x, screen_top, screen_left, screen_bottom, screen_right)
    pad.refresh(0, 0, 0, 0, render_h, render_w)

    # Keep program open until any key press occurs
    stdscr.getch()

curses.wrapper(main)